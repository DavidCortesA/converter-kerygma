// Los nombres de idioma se muestran siempre en su propio idioma.
const LANGUAGE_NAMES = { es: 'Español', en: 'English' };

let currentLang = 'es';

function setLanguage(lang) {
  currentLang = STRINGS[lang] ? lang : 'es';
  document.documentElement.lang = currentLang;
}

function t(key, vars = {}) {
  let value = STRINGS[currentLang][key] ?? STRINGS.es[key] ?? key;
  if (typeof value === 'object') value = vars.n === 1 ? value.one : value.other;
  return value.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? vars[name] : `{${name}}`));
}

// Como t(), pero si el idioma actual no tiene la clave usa la alternativa
// (p. ej. dz.sub.image solo existe en español por el género de «fotos»).
function tOr(key, fallback, vars) {
  return key in STRINGS[currentLang] ? t(key, vars) : t(fallback, vars);
}
